#!/usr/bin/env python3
"""
Build the Cloudflare Worker's files from index.html.

index.html is the single source of truth: it holds the UI, fictional sample
data, and — between the persistence markers — browser-only demo storage.
This script produces:

    src/app.html   the same UI with _sync.js swapped in for the Worker
    seed.sql       the starting data as D1 upserts

Everything shared lives in index.html, so a UI change is made once.

    python build.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).parent
SRC = ROOT / "index.html"
SYNC = ROOT / "_sync.js"
APP_OUT = ROOT / "src" / "app.html"
SEED_OUT = ROOT / "seed.sql"

PERSISTENCE_START = "/* ============================ persistence ============================ */"
PERSISTENCE_END = "/* ============================ actions ============================ */"
SEED_RE = r'<script type="application/json" id="seed">(.*?)</script>'

# Bump whenever the seed content changes, or re-running seed.sql is ignored
# by the last-write-wins guard in the upserts below.
SEED_STAMP = 1767225600000  # 2026-01-01, before any real demo edits

SIGN_OUT = ('  <main id="view"></main>\n'
            '  <p class="note" style="text-align:center;margin-top:28px">'
            '<a href="/logout" style="color:var(--silver)">Sign out of this phone</a></p>\n</div>')


def must(old, new, s, what):
    if old not in s:
        sys.exit(f"build failed: could not find {what}\n  looking for: {old[:110]!r}")
    return s.replace(old, new, 1)


def build_app(src):
    # Data comes from D1, not an embedded blob.
    s = re.sub(SEED_RE + r"\n\n", "", src, flags=re.S)

    # The one real difference between the two builds.
    try:
        start = s.index(PERSISTENCE_START)
        end = s.index(PERSISTENCE_END)
    except ValueError:
        sys.exit("build failed: persistence markers missing from index.html")
    s = s[:start] + SYNC.read_text(encoding="utf-8") + s[end:]

    # The browser demo is already a complete document. The Worker build
    # swaps in D1 sync, removes the demo notice and adds a sign-out link.
    s, notice_count = re.subn(r'<div class="demo-notice">.*?</div>\n', "", s, count=1, flags=re.S)
    if notice_count != 1:
        sys.exit("build failed: demo notice missing")
    s = must('  <main id="view"></main>\n</div>', SIGN_OUT, s, "main close")

    for leftover in ("window.claude", "{{ERROR}}", 'id="seed"'):
        if leftover in s:
            sys.exit(f"build failed: {leftover} survived into src/app.html")

    APP_OUT.write_text(s, encoding="utf-8")
    print(f"src/app.html written ({len(s):,} bytes)")


def build_seed(src):
    raw = re.search(SEED_RE, src, re.S)
    if not raw:
        sys.exit("build failed: no seed block in index.html")
    data = json.loads(raw.group(1))

    def q(text):
        return "'" + text.replace("'", "''") + "'"

    def upsert(table, record):
        record = dict(record, updatedAt=SEED_STAMP)
        blob = json.dumps(record, ensure_ascii=False, separators=(",", ":"))
        key = "'app'" if table == "settings" else q(record["id"])
        return (f"INSERT INTO {table} (id, data, updated_at) VALUES ({key}, {q(blob)}, {SEED_STAMP})\n"
                f"  ON CONFLICT(id) DO UPDATE SET data=excluded.data, updated_at=excluded.updated_at\n"
                f"  WHERE excluded.updated_at > {table}.updated_at;")

    lines = ["-- Job Book fictional sample data. Generated by build.py; do not edit.",
             "-- The people, addresses and notes here are invented for the public trial.",
             "-- Safe to re-run: a row only overwrites an older one, so real edits survive.", ""]
    counts = {}
    for table in ("clients", "visits", "notes"):
        rows = data.get(table, [])
        counts[table] = len(rows)
        lines.append(f"-- {table}")
        lines += [upsert(table, r) for r in rows]
        lines.append("")
    lines.append("-- settings")
    lines.append(upsert("settings", data["settings"]))

    SEED_OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("seed.sql written (" + ", ".join(f"{n} {t}" for t, n in counts.items()) + ")")


if __name__ == "__main__":
    source = SRC.read_text(encoding="utf-8")
    build_app(source)
    build_seed(source)
